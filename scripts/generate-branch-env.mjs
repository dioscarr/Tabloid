import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const args = Object.fromEntries(process.argv.slice(2).map((value, index, values) => {
  if (!value.startsWith('--')) return [value, true]
  const key = value.slice(2)
  const next = values[index + 1]
  return [key, next && !next.startsWith('--') ? next : true]
}))

const branch = String(args.branch || process.env.GIT_BRANCH || '').trim()
const output = resolve(String(args.output || '.env.local'))
const tailnetDomain = String(args['tailnet-domain'] || 'tail70b7f1.ts.net').trim()

if (!branch) throw new Error('Provide --branch <name> or set GIT_BRANCH.')
if (!/^[A-Za-z0-9._/-]{1,120}$/.test(branch) || branch.includes('..')) throw new Error('Branch contains unsupported characters.')
if (!/^[a-z0-9.-]+$/i.test(tailnetDomain)) throw new Error('Tailnet domain is invalid.')

const previewId = (name) => {
  let slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'branch'
  slug = slug.slice(0, 38).replace(/-$/, '')
  return `${slug}-${createHash('sha256').update(name).digest('hex').slice(0, 6)}`
}

const products = {
  main: ['daily-echo', 'The Daily Echo'],
  'big-news': ['big-news', 'Big News'],
  tech: ['tech', 'Tech'],
  admin: ['admin', 'Admin'],
  'app-gallery': ['app-gallery', 'App Gallery'],
}

const [appSlug, appName] = products[branch] || [previewId(branch), branch]
const hostname = branch === 'main' ? 'tabloid' : `tabloid-${previewId(branch)}`
const values = {
  APP_BRANCH: branch,
  APP_SLUG: appSlug,
  VITE_APP_NAME: appName,
  VITE_APP_ENV: branch === 'main' ? 'production' : 'preview',
  VITE_APP_URL: `https://${hostname}.${tailnetDomain}/`,
  VITE_API_BASE_URL: '/api/v1',
  VITE_AUTH_BASE_URL: `https://auth.${tailnetDomain}/`,
  // Public tailnet origin of the deployed Admin API. Not a credential.
  ...(branch === 'app-gallery' ? { VITE_ADMIN_API_URL: `https://tabloid-api-14c252.${tailnetDomain}` } : {}),
}

const body = [
  '# Generated by scripts/generate-branch-env.mjs.',
  '# Public application configuration only. Do not add secrets to this file.',
  ...Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`),
  '',
].join('\n')

await writeFile(output, body, { encoding: 'utf8', mode: 0o600 })
console.log(`Generated ${output} for branch ${branch}`)
